# Route 1 (GET): Homepage Form Display
@app.route('/')
def home():
    return render_template_string(INDEX_HTML)

# Route 2 (POST): Form Handler & Input Checker
@app.route('/register', methods=['POST'])
def register():
    name = request.form.get('name', '').strip()
    email = request.form.get('email', '').strip()
    course = request.form.get('course', '').strip()

    # Basic Validation Rule Check
    if not name or not email or not course:
        return render_template_string(INDEX_HTML, error="All form fields are mandatory!")

    if "@" not in email:
        return render_template_string(INDEX_HTML, error="Please enter a valid email structure.")

    student_record = {"name": name, "email": email, "course": course}
    registered_students.append(student_record)

    return render_template_string(RESULT_HTML, student=student_record)

# Route 3 (GET): Dynamic System Info Page
@app.route('/about')
def about():
    count = len(registered_students)
    return f"""
    <body style=\"font-family: sans-serif; padding: 30px;\">
        <h2>About Registration App</h2>
        <p>This beginner project tracks live form submissions dynamically.</p>
        <p><strong>Live Database Metric:</strong> {count} students registered in this session.</p>
        <a href=\"/\">← Go Back Form Screen</a>
    </body>
    """

def run_flask():
    app.run(host="0.0.0.0", port=5001,
            debug=False, use_reloader=False)

Thread(target=run_flask, daemon=True).start()

output.serve_kernel_port_as_window(5001)

